package ofp.codegen;

import ofp.parser.OFPBaseVisitor;
import ofp.parser.OFPParser;
import ofp.symbols.Scope;
import ofp.symbols.Symbol;
import ofp.types.OFPType;
import org.antlr.v4.runtime.ParserRuleContext;
import org.antlr.v4.runtime.tree.ParseTreeProperty;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/** Translates a validated OFP program into readable Python source. */
public class PythonGenerator extends OFPBaseVisitor<String> {

  private final ParseTreeProperty<Scope> scopes;
  private final ParseTreeProperty<OFPType> expressionTypes;
  private boolean needsIntegerDivision = false;
  private final Map<Symbol, String> variableNames = new HashMap<>();
  private final Set<String> usedVariableNames = new HashSet<>();
  private Scope currentScope;

  private int depth = 0;

  private final Map<Integer, String> indentCache = new HashMap<>();
  private String indent() { return indent(depth); }
  private String indent(int d) { return indentCache.computeIfAbsent(d, k -> "    ".repeat(k)); }

  // Indent single-statement bodies just like braced blocks.
  private String emitBody(OFPParser.StmtOrBlockContext b) {
    if (b.block() != null) {
      // The block visitor supplies the indentation.
      return visit(b.block());
    } else {
      // A single statement needs one extra indentation level.
      depth++;
      String s = visit(b.stmt());
      depth--;
      return s;
    }
  }

  // Avoid collisions with Python keywords and built-ins.
  private static final Set<String> RESERVED = new HashSet<>(Arrays.asList(
    "False","None","True","and","as","assert","async","await","break","class","continue","def","del","elif","else",
    "except","finally","for","from","global","if","import","in","is","lambda","nonlocal","not","or","pass","raise",
    "return","try","while","with","yield",
    "len","print","sum","max","min","list","str","int","float","bool","range","object","input","open","map","ord","zip"
  ));
  private static String safeID(String id){ return RESERVED.contains(id) ? ("ofp_" + id) : id; }

  // Python has function scope, so give shadowed block variables distinct target names.
  private String variableName(String sourceName) {
    Symbol symbol = currentScope.resolve(sourceName);
    return variableNames.computeIfAbsent(symbol, key -> {
      String base = safeID(sourceName);
      String candidate = base;
      int suffix = 2;
      while (!usedVariableNames.add(candidate)) candidate = base + "_" + suffix++;
      return candidate;
    });
  }

  private void resetVariables() {
    variableNames.clear();
    usedVariableNames.clear();
  }

  public PythonGenerator(ParseTreeProperty<Scope> scopes, ParseTreeProperty<OFPType> expressionTypes){
    this.scopes = scopes;
    this.expressionTypes = expressionTypes;
  }

  // program
  @Override
  public String visitProgram(OFPParser.ProgramContext ctx) {
    currentScope = scopes.get(ctx);
    StringBuilder out = new StringBuilder();

    ParserRuleContext mainNode = null;
    for (int i = 0; i < ctx.getChildCount(); i++) {
      if (!(ctx.getChild(i) instanceof ParserRuleContext p)) continue;
      if (p instanceof OFPParser.MainContext) mainNode = p;
      else if (p instanceof OFPParser.FunctionDeclContext) out.append(visit(p));
    }
    if (mainNode != null) out.append(visit(mainNode));
    String header = "# Generated by the OFP compiler.\n\n";
    if (needsIntegerDivision) {
      header += "def _ofp_div(left, right):\n"
          + "    # Integer division truncates toward zero, including negative operands.\n"
          + "    quotient = abs(left) // abs(right)\n"
          + "    return -quotient if (left < 0) != (right < 0) else quotient\n\n";
    }
    return header + out;
  }

  // main
  @Override
  public String visitMain(OFPParser.MainContext ctx) {
    currentScope = scopes.get(ctx);
    resetVariables();
    StringBuilder buf = new StringBuilder();
    buf.append("def _ofp_main():\n");

    int prevDepth = depth;

    depth = 0;
    buf.append(visit(ctx.block()));
    buf.append("\nif __name__ == '__main__':\n    _ofp_main()\n");
    depth = 0;

    depth = prevDepth;
    currentScope = currentScope.getEnclosingScope();
    return buf.toString();
  }

  // Function declarations
  @Override
  public String visitFunctionDecl(OFPParser.FunctionDeclContext ctx) {
    currentScope = scopes.get(ctx);
    resetVariables();
    StringBuilder buf = new StringBuilder();

    String name = safeID(ctx.ID().getText());
    List<String> params = new ArrayList<>();
    if (ctx.paramList() != null) {
      for (OFPParser.ParamContext p : ctx.paramList().param()) {
        params.add(variableName(p.ID().getText()));
      }
    }

    buf.append("def ").append(name).append("(")
      .append(String.join(", ", params)).append("):\n");

    buf.append(visit(ctx.block()));

    buf.append("\n");
    currentScope = currentScope.getEnclosingScope();
    return buf.toString();
  }

  // block

  @Override
  public String visitBlock(OFPParser.BlockContext ctx) {
    currentScope = scopes.get(ctx);
    StringBuilder buf = new StringBuilder();
    depth++;
    for (OFPParser.StmtContext s : ctx.stmt()) {
      String line = visit(s);
      if (line != null && !line.isEmpty()) buf.append(line);
    }
    if (buf.toString().strip().isEmpty()) buf.append(indent()).append("pass\n");
    depth--;
    currentScope = currentScope.getEnclosingScope();
    return buf.toString();
  }

  // Statements
  @Override
  public String visitVarDeclStmt(OFPParser.VarDeclStmtContext ctx) {
    OFPParser.VarDeclContext v = ctx.varDecl();
    if (v.expr() != null) {
      return indent() + variableName(v.ID().getText()) + " = " + visit(v.expr()) + "\n";
    }
    String initial = switch (v.type().getText()) {
      case "int" -> "0";
      case "float" -> "0.0";
      case "bool" -> "False";
      case "char" -> "'\\0'";
      default -> "None";
    };
    return indent() + variableName(v.ID().getText()) + " = " + initial + "\n";
  }

  @Override
  public String visitAssignStmt(OFPParser.AssignStmtContext ctx) {
    String id = variableName(ctx.assignment().ID().getText());
    String val = visit(ctx.assignment().expr());
    return indent() + id + " = " + val + "\n";
  }

  @Override
  public String visitArrayAssignStmt(OFPParser.ArrayAssignStmtContext ctx) {
    String id = variableName(ctx.arrayAssign().ID().getText());
    String idx = visit(ctx.arrayAssign().expr(0));
    String val = visit(ctx.arrayAssign().expr(1));
    return indent() + id + "[" + idx + "] = " + val + "\n";
  }

  @Override
  public String visitIfStmtRule(OFPParser.IfStmtRuleContext ctx) {
    OFPParser.IfStmtContext i = ctx.ifStmt();
    StringBuilder buf = new StringBuilder();

    buf.append(indent()).append("if ").append(visit(i.expr())).append(":\n");
    buf.append(emitBody(i.stmtOrBlock(0)));

    if (i.stmtOrBlock().size() == 2) {
      buf.append(indent()).append("else:\n");
      buf.append(emitBody(i.stmtOrBlock(1)));
    }
    return buf.toString();
  }

  @Override
  public String visitWhileStmtRule(OFPParser.WhileStmtRuleContext ctx) {
    String cond = visit(ctx.whileStmt().expr());
    StringBuilder buf = new StringBuilder();
    buf.append(indent()).append("while ").append(cond).append(":\n");
    buf.append(emitBody(ctx.whileStmt().stmtOrBlock()));
    return buf.toString();
  }

  @Override
  public String visitReturnStmtRule(OFPParser.ReturnStmtRuleContext ctx) {
    OFPParser.ReturnStmtContext r = ctx.returnStmt();
    if (r.expr() == null) return indent() + "return\n";
    return indent() + "return " + visit(r.expr()) + "\n";
  }

  @Override
  public String visitPrintStmtRule(OFPParser.PrintStmtRuleContext ctx) {
    String which = ctx.printStmt().getStart().getText();
    String e = visit(ctx.printStmt().expr());
    if ("print".equals(which)) return indent() + "print(" + e + ", end='')\n";
    else return indent() + "print(" + e + ")\n";
  }

  @Override
  public String visitExprStmtRule(OFPParser.ExprStmtRuleContext ctx) {
    return indent() + visit(ctx.exprStmt().expr()) + "\n";
  }

  // stmtOrBlock
  @Override
  public String visitStmtOrBlock(OFPParser.StmtOrBlockContext ctx) {
    if (ctx.stmt() != null) return visit(ctx.stmt());
    if (ctx.block() != null) return visit(ctx.block());
    return indent() + "pass\n";
  }

  // Expressions
 @Override
  public String visitMulDivExpr(OFPParser.MulDivExprContext ctx) {
    String left = visit(ctx.expr(0));
    String right = visit(ctx.expr(1));
    String op = ctx.getChild(1).getText();
    if ("/".equals(op) && expressionTypes.get(ctx) == OFPType.INT) {
      needsIntegerDivision = true;
      return "_ofp_div(" + left + ", " + right + ")";
    }
    return "(" + left + " " + op + " " + right + ")";
  }
  @Override
  public String visitAddSubExpr(OFPParser.AddSubExprContext ctx) {
    String left = visit(ctx.expr(0));
    String right = visit(ctx.expr(1));
    String op = ctx.getChild(1).getText();
    return "(" + left + " " + op + " " + right + ")";
  }
  @Override
  public String visitCompExpr(OFPParser.CompExprContext ctx) {
    String left = visit(ctx.expr(0));
    String right = visit(ctx.expr(1));
    String op = ctx.getChild(1).getText();
    return "(" + left + " " + op + " " + right + ")";
  }
  @Override public String visitUnaryMinusExpr(OFPParser.UnaryMinusExprContext ctx) {
    return "-" + visit(ctx.expr());
  }
  @Override public String visitFuncCallExpr(OFPParser.FuncCallExprContext ctx) {
    String name = safeID(ctx.ID().getText());
    String args = "";
    if (ctx.argList() != null) {
      List<String> parts = new ArrayList<>();
      for (OFPParser.ExprContext e : ctx.argList().expr()) parts.add(visit(e));
      args = String.join(", ", parts);
    }
    return name + "(" + args + ")";
  }
  @Override public String visitArrayAccessExpr(OFPParser.ArrayAccessExprContext ctx) {
    return variableName(ctx.ID().getText()) + "[" + visit(ctx.expr()) + "]";
  }
  @Override public String visitLengthExpr(OFPParser.LengthExprContext ctx) {
    return "len(" + visit(ctx.expr()) + ")";
  }
  @Override public String visitNewArrayExpr(OFPParser.NewArrayExprContext ctx) {
    String base = ctx.baseType().getText();
    String n = visit(ctx.expr());
    switch (base) {
      case "int":   return "[0]*(" + n + ")";
      case "float": return "[0.0]*(" + n + ")";
      default:      return "['\\0']*(" + n + ")";
    }
  }
  @Override public String visitLiteralExpr(OFPParser.LiteralExprContext ctx) { return visit(ctx.literal()); }
  @Override public String visitIdExpr(OFPParser.IdExprContext ctx) { return variableName(ctx.ID().getText()); }
  @Override public String visitParExpr(OFPParser.ParExprContext ctx) { return "(" + visit(ctx.expr()) + ")"; }

  // Literals
  @Override public String visitIntLiteral(OFPParser.IntLiteralContext ctx) { return ctx.getText(); }
  @Override public String visitFloatLiteral(OFPParser.FloatLiteralContext ctx) { return ctx.getText(); }
  @Override
  public String visitBoolLiteral(OFPParser.BoolLiteralContext ctx) {
    String t = ctx.getText();
    return "true".equals(t) ? "True" : "False";
  }

  @Override public String visitCharLiteral(OFPParser.CharLiteralContext ctx) { return ctx.getText(); }
  @Override public String visitStringLiteral(OFPParser.StringLiteralContext ctx) { return ctx.getText(); }

  @Override public String visitArrayLiteral(OFPParser.ArrayLiteralContext ctx) {
    List<String> parts = new ArrayList<>();
    if (ctx.arrayLit().expr() != null && !ctx.arrayLit().expr().isEmpty()) {
      for (OFPParser.ExprContext e : ctx.arrayLit().expr()) parts.add(visit(e));
    }
    return "[" + String.join(", ", parts) + "]";
  }
}
